create extension if not exists vector;

create table if not exists movies (
  id bigint generated by default as identity primary key,
  tmdb_id bigint unique,
  title text not null,
  release_year integer,
  poster_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists movie_chunks (
  id bigint generated by default as identity primary key,
  movie_id bigint references movies(id) on delete cascade,
  content text not null,
  content_hash text not null unique,
  embedding vector(1536) not null,
  created_at timestamptz not null default now()
);

create index if not exists movie_chunks_embedding_idx
  on movie_chunks using hnsw (embedding vector_cosine_ops);

create table if not exists recommendation_requests (
  id uuid primary key default gen_random_uuid(),
  user_id text,
  favorite_movie text not null,
  mood text not null,
  favorite_genre text not null,
  status text not null check (status in ('pending', 'completed', 'failed')),
  model text,
  latency_ms integer,
  created_at timestamptz not null default now()
);

create index if not exists recommendation_requests_user_created_idx
  on recommendation_requests (user_id, created_at desc);

create table if not exists recommendation_results (
  id bigint generated by default as identity primary key,
  request_id uuid not null references recommendation_requests(id) on delete cascade,
  rank integer not null check (rank > 0),
  title text not null,
  release_year text not null,
  content text not null,
  poster_url text,
  unique (request_id, rank)
);

create or replace function match_movies (
  query_embedding vector(1536),
  match_threshold float,
  match_count int
)
returns table (id bigint, content text, similarity float)
language sql stable
as $$
  select movie_chunks.id,
    movie_chunks.content,
    1 - (movie_chunks.embedding <=> query_embedding) as similarity
  from movie_chunks
  where movie_chunks.embedding <=> query_embedding < 1 - match_threshold
  order by movie_chunks.embedding <=> query_embedding
  limit least(match_count, 10);
$$;

alter table recommendation_requests enable row level security;
alter table recommendation_results enable row level security;

create policy "users can read their own recommendation requests"
  on recommendation_requests for select
  using (user_id = auth.uid()::text);

create policy "users can read their own recommendation results"
  on recommendation_results for select
  using (exists (
    select 1 from recommendation_requests
    where recommendation_requests.id = recommendation_results.request_id
      and recommendation_requests.user_id = auth.uid()::text
  ));
